const editionFiles: Record<DecreeEdition, string> = {
  Foil: 'foil',
  Holographic: 'holographic',
  Polychrome: 'polychrome',
  Negative: 'negative',
}

export function getDecreeEditionArt(
  decreeId?: string,
  edition?: DecreeEdition
): string | undefined {
  if (
    !decreeId ||
    !edition ||
    !decreeEditionArtIds.has(decreeId) ||
    !Object.prototype.hasOwnProperty.call(editionFiles, edition)
  )
    return undefined
  return withBasePath(
    `assets/illustrations/decree-editions/${decreeId}/${editionFiles[edition]}.webp`
  )
}
