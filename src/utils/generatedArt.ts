export type ControlArtId = keyof typeof generatedArtPaths.controls
export type AchievementArtId = keyof typeof generatedArtPaths.achievements
export type GeneratedArtCategory = keyof typeof generatedArtPaths
/** Own-key lookup prevents inherited object keys from becoming image URLs. */
export function getGeneratedArt(
  category: GeneratedArtCategory,
  id?: string
): string | undefined {
  const assets: Readonly<Record<string, string>> = generatedArtPaths[category]
  return id && Object.prototype.hasOwnProperty.call(assets, id)
    ? withBasePath(assets[id])
    : undefined
}
export function getControlArt(id: ControlArtId): string {
  return withBasePath(generatedArtPaths.controls[id])
}

